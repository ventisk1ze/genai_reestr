"""Исключения домена → HTTP-коды (маппинг — в registry/api).

Каждое исключение — один код ответа и один формат {"error": текст}:
    BadRequest  → 400 — некорректный запрос (валидация тел и параметров)
    AuthError   → 401 (+ "login": true) — нет сессии или неверный PIN
    Forbidden   → 403 — действие не разрешено этому пользователю
    Conflict    → 409 — конфликт версий (задачу/справочник изменил другой)
    Locked      → 429 — слишком много неверных попыток входа подряд
"""


class BadRequest(Exception):
    """400: некорректный запрос — понятный текст человеку, без трассировки."""


class Conflict(Exception):
    """409: данные успел изменить кто-то другой (проверка версий)."""


class AuthError(Exception):
    """401: нет сессии или PIN неверный."""


class Forbidden(Exception):
    """403: действие не разрешено этому пользователю (только админ, не тот этап или не та роль в задаче)."""


class Locked(Exception):
    """429: слишком много неверных PIN подряд."""
